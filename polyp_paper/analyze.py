"""Aggregate the per-image CSVs of one result bundle into tables (markdown/csv) and figures (png).
python analyze.py --bundle <folder that contains eval/ and runs/> --out <output folder> [--seq splits_lists/clinicdb_sequences.csv]

Rules: per-image metrics (from evaluate.py); several seeds are averaged per image before any test; confidence intervals are
percentile bootstraps over IMAGES (optimistic: frames of one video are correlated) and, for ClinicDB, also over the official
video sequences; p-values are Wilcoxon signed-rank on paired images with Holm correction over all tests shown."""
