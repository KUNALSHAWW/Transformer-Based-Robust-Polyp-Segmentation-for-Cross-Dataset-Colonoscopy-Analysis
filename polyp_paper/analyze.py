def holm(p):
    p = np.asarray(p, float); o = np.argsort(p); m = len(p); adj = np.empty(m); run = 0
    for r, i in enumerate(o):
        run = max(run, (m - r) * p[i]); adj[i] = min(1.0, run)
    return adj


def load(bundle):
    fs = sorted(glob.glob(os.path.join(bundle, "eval", "*", "*", "seed*", "per_image.csv")))
    assert fs, "no per_image.csv found under " + bundle
    df = pd.concat([pd.read_csv(f) for f in fs], ignore_index=True)
    df["area_frac"] = 10 ** (3 * df["t_gt"] - 3)                     # lesion area fraction recovered from the size code (floor 0.1%)
    df["overlay"] = df["dataset"].str.endswith("+overlay"); df["set"] = df["dataset"].str.replace("+overlay", "", regex=False)
    keys = ["protocol", "variant", "set", "overlay", "image"]
    num = METRICS + ["t_hat", "t_gt", "area_frac", "gt_area"]
    return df.groupby(keys, as_index=False)[num].mean()


def cluster_ci(diff, clusters, n_boot=5000, seed=0):
    """bootstrap over clusters (video sequences): resample sequences, average the per-image differences of the chosen sequences."""
    rng = np.random.default_rng(seed); ids = np.unique(clusters); idx = {c: np.where(clusters == c)[0] for c in ids}
    means = [np.nanmean(np.concatenate([diff[idx[c]] for c in rng.choice(ids, len(ids))])) for _ in range(n_boot)]
    return float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--bundle", required=True); ap.add_argument("--out", required=True)
    ap.add_argument("--seq", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "splits_lists", "clinicdb_sequences.csv"))
    a = ap.parse_args(); os.makedirs(a.out, exist_ok=True)
    df = load(a.bundle); clean = df[~df.overlay]; md = ["# Analysis (auto-generated by analyze.py)\n"]
    seq = pd.read_csv(a.seq).set_index("frame")["sequence"].to_dict()
    n_seeds = len(glob.glob(os.path.join(a.bundle, "eval", "A", "base", "seed*")))
    md.append(f"Seeds per version in this bundle: **{n_seeds}**. {'With one seed the seed-to-seed variation is unknown, so small differences must not be read as real.' if n_seeds < 2 else ''}\n")

    for proto in sorted(clean.protocol.unique()):
        d = clean[clean.protocol == proto]; variants = [v for v in VARIANT_ORDER if v in set(d.variant)]; sets = [s for s in (B_SETS if proto != "A" else ["Kvasir120", "ClinicDB612", "ColonDB", "ETIS", "CVC300"]) if s in set(d.set)]
        # ---- Table 1: means with 95% CI ----
        rows = []
        for v in variants:
            for s in sets:
                x = d[(d.variant == v) & (d.set == s)]; lo, hi = bootstrap_ci(x.dice.values)
                rows.append(dict(protocol=proto, version=v, test_set=s, n=len(x), dice=x.dice.mean(), dice_ci=f"{lo:.3f}-{hi:.3f}", iou=x.iou.mean(), precision=x.precision.mean(),
                                 recall=x.recall.mean(), f2=x.f2.mean(), hd95_mean=x.hd95.mean(), hd95_median=x.hd95.median()))
        t1 = pd.DataFrame(rows); t1.to_csv(os.path.join(a.out, f"table_results_{proto}.csv"), index=False)
        md.append(f"\n## Protocol {proto}: results per test set (mean over images; Dice with 95% bootstrap CI over images)\n")
        md.append("| version | test set | n | Dice [95% CI] | IoU | Precision | Recall | F2 | HD95 mean / median (px) |\n|---|---|---|---|---|---|---|---|---|")
        for r in rows:
            md.append(f"| {r['version']} | {r['test_set']} | {r['n']} | {r['dice']:.4f} [{r['dice_ci']}] | {r['iou']:.4f} | {r['precision']:.4f} | {r['recall']:.4f} | {r['f2']:.4f} | {r['hd95_mean']:.1f} / {r['hd95_median']:.1f} |")
        # ---- Table 2: paired comparison with base ----
        if "base" in variants and len(variants) > 1:
            prow = []
            for v in variants:
                if v == "base": continue
                for s in sets:
                    b = d[(d.variant == "base") & (d.set == s)].set_index("image"); x = d[(d.variant == v) & (d.set == s)].set_index("image"); common = b.index.intersection(x.index)
                    for m in ("dice", "hd95"):
                        pc = paired_compare(x.loc[common, m].values, b.loc[common, m].values)
                        cl = ""
                        if s.startswith("ClinicDB"):
                            cl = "%.4f to %.4f" % cluster_ci((x.loc[common, m].values - b.loc[common, m].values), np.array([seq[int(i)] for i in common]))
                        prow.append(dict(version=v, test_set=s, metric=m, mean_diff=pc["mean_diff"], ci_lo=pc["ci95"][0], ci_hi=pc["ci95"][1], p_raw=pc["wilcoxon_p"], cluster_ci=cl, n=pc["n"]))
            t2 = pd.DataFrame(prow); t2["p_holm"] = np.nan
            for m in ("dice", "hd95"):
                msk = t2.metric == m; t2.loc[msk, "p_holm"] = holm(t2.loc[msk, "p_raw"].values)
            t2.to_csv(os.path.join(a.out, f"table_paired_vs_base_{proto}.csv"), index=False)
            md.append(f"\n## Protocol {proto}: difference to `base` on the same images (positive Dice difference = better; for HD95 negative = better)\n")
            md.append("| version | test set | metric | mean difference [95% CI] | p (Wilcoxon) | p (Holm) | extra CI over video sequences (ClinicDB only) |\n|---|---|---|---|---|---|---|")
            for r in prow:
                rr = t2[(t2.version == r["version"]) & (t2.test_set == r["test_set"]) & (t2.metric == r["metric"])].iloc[0]
                md.append(f"| {r['version']} | {r['test_set']} | {r['metric']} | {r['mean_diff']:+.4f} [{r['ci_lo']:+.4f}, {r['ci_hi']:+.4f}] | {r['p_raw']:.3g} | {rr['p_holm']:.3g} | {r['cluster_ci']} |")
            # forest plot of Dice differences
            fig, axes = plt.subplots(1, len(sets), figsize=(3.3 * len(sets), 3.6), sharey=True)
            for ax, s in zip(np.atleast_1d(axes), sets):
                q = t2[(t2.test_set == s) & (t2.metric == "dice")]
                for k, (_, r) in enumerate(q.iterrows()):
                    ax.errorbar(r.mean_diff, k, xerr=[[r.mean_diff - r.ci_lo], [r.ci_hi - r.mean_diff]], fmt="o", color=COL[r.version], capsize=3)
                ax.axvline(0, color="k", lw=.8); ax.set_yticks(range(len(q))); ax.set_yticklabels([NICE[v] for v in q.version], fontsize=8); ax.set_title(s, fontsize=10); ax.set_xlabel("Dice difference to base", fontsize=8); ax.grid(alpha=.3)
            plt.suptitle(f"Protocol {proto}: change in Dice compared with the original model (dot = mean, bar = 95% CI)", fontsize=10); plt.tight_layout(); plt.savefig(os.path.join(a.out, f"fig_forest_{proto}.png"), dpi=170); plt.close()
        # ---- Figure: per-image Dice boxplots ----
        fig, axes = plt.subplots(1, len(sets), figsize=(3.4 * len(sets), 4), sharey=True)
        for ax, s in zip(np.atleast_1d(axes), sets):
            data = [d[(d.variant == v) & (d.set == s)].dice.values for v in variants]
            bp = ax.boxplot(data, patch_artist=True, showmeans=True, meanprops=dict(marker="D", markerfacecolor="white", markeredgecolor="k", markersize=4), flierprops=dict(markersize=2), widths=.6)
            for p_, v in zip(bp["boxes"], variants): p_.set_facecolor(COL[v]); p_.set_alpha(.75)
            ax.set_xticks(range(1, len(variants) + 1)); ax.set_xticklabels([v.replace("roy_", "r_") for v in variants], rotation=45, fontsize=7); ax.set_title(f"{s} (n={len(data[0])})", fontsize=10); ax.grid(alpha=.3, axis="y")
        np.atleast_1d(axes)[0].set_ylabel("per-image Dice"); plt.suptitle(f"Protocol {proto}: spread of per-image Dice (diamond = mean)", fontsize=10); plt.tight_layout(); plt.savefig(os.path.join(a.out, f"fig_dice_boxplots_{proto}.png"), dpi=170); plt.close()
        # ---- size bins ----
        def binned(frame):
            out = []
            for lo, hi, name in BINS:
                x = frame[(frame.area_frac >= lo) & (frame.area_frac < hi)]; out.append((name, len(x), x))
            return out
        groups = {s: d[d.set == s] for s in sets}
        ext = [s for s in sets if s not in ("Kvasir120", "Kvasir100", "CVC300")]   # CVC300 = 60 pictures that are byte-identical to ColonDB pictures, so it is not pooled again
        if ext: groups["all external pooled"] = d[d.set.isin(ext)]
        md.append(f"\n## Protocol {proto}: Dice by polyp size (area as share of the picture; size recovered from the size code, polyps under 0.1% count as 0.1%)\n")
        md.append("| group | size bin | n images | " + " | ".join(variants) + " |\n|---|---|---|" + "---|" * len(variants))
        fig, axes = plt.subplots(1, len(groups), figsize=(3.4 * len(groups), 3.8), sharey=True)
        for ax, (g, fr) in zip(np.atleast_1d(axes), groups.items()):
            w = .8 / len(variants)
            for k, v in enumerate(variants):
                vals = []
                for name, n, x in binned(fr[fr.variant == v]): vals.append(x.dice.mean() if n else np.nan)
                ax.bar(np.arange(len(BINS)) + k * w, vals, w, color=COL[v], label=v if g == list(groups)[0] else None)
            ns = [n for _, n, _ in binned(fr[fr.variant == variants[0]])]
            ax.set_xticks(np.arange(len(BINS)) + .4 - w / 2); ax.set_xticklabels([f"{b[2]}\n(n={n})" for b, n in zip(BINS, ns)], fontsize=7); ax.set_title(g, fontsize=9); ax.grid(alpha=.3, axis="y"); ax.set_ylim(0.2, 1.0)
            for (name, n, _), i in zip(binned(fr[fr.variant == variants[0]]), range(len(BINS))):
                md.append(f"| {g} | {name} | {n} | " + " | ".join(f"{(lambda t: t[2].dice.mean() if t[1] else float('nan'))(binned(fr[fr.variant == v])[i]):.3f}" for v in variants) + " |")
        np.atleast_1d(axes)[0].set_ylabel("mean Dice"); np.atleast_1d(axes)[0].legend(fontsize=6); plt.suptitle(f"Protocol {proto}: Dice by polyp size", fontsize=10); plt.tight_layout(); plt.savefig(os.path.join(a.out, f"fig_by_size_{proto}.png"), dpi=170); plt.close()
        md.append(f"\n## Protocol {proto}: share of pictures where the polyp is mostly missed (Dice below 0.5; in brackets: almost nothing found, Dice below 0.01), by polyp size, all external sets pooled\n")
        md.append("| size bin | n images | " + " | ".join(variants) + " |\n|---|---|" + "---|" * len(variants))
        if ext:
            fr_ = d[d.set.isin(ext)]
            for lo, hi, name in BINS:
                xs = [fr_[(fr_.variant == v) & (fr_.area_frac >= lo) & (fr_.area_frac < hi)] for v in variants]
                md.append(f"| {name} | {len(xs[0])} | " + " | ".join(f"{(x.dice < .5).mean() * 100:.0f}% (empty-mask {(x.dice < .01).mean() * 100:.0f}%)" if len(x) else "-" for x in xs) + " |")
        # ---- overlay sensitivity ----
        o = df[(df.protocol == proto) & (df.set.isin(["Kvasir120", "Kvasir100"]))]
        if o.overlay.any():
            md.append(f"\n## Protocol {proto}: sensitivity to synthetic screen stickers pasted on the test pictures (Dice with stickers minus without)\n")
            md.append("| version | mean Dice clean | mean Dice with stickers | mean difference [95% CI] |\n|---|---|---|---|")
            fig, ax = plt.subplots(figsize=(5.5, 3.4)); k = 0
            for v in variants:
                c = o[(o.variant == v) & (~o.overlay)].set_index("image").dice; s_ = o[(o.variant == v) & (o.overlay)].set_index("image").dice; com = c.index.intersection(s_.index)
                pc = paired_compare(s_.loc[com].values, c.loc[com].values); md.append(f"| {v} | {c.loc[com].mean():.4f} | {s_.loc[com].mean():.4f} | {pc['mean_diff']:+.4f} [{pc['ci95'][0]:+.4f}, {pc['ci95'][1]:+.4f}] |")
                ax.errorbar(pc["mean_diff"], k, xerr=[[pc["mean_diff"] - pc["ci95"][0]], [pc["ci95"][1] - pc["mean_diff"]]], fmt="o", color=COL[v], capsize=3); k += 1
            ax.axvline(0, color="k", lw=.8); ax.set_yticks(range(len(variants))); ax.set_yticklabels([NICE[v] for v in variants], fontsize=8); ax.set_xlabel("Dice change when stickers are added"); ax.grid(alpha=.3)
            ax.set_title(f"Protocol {proto}: does a pasted sticker hurt?", fontsize=10); plt.tight_layout(); plt.savefig(os.path.join(a.out, f"fig_sticker_probe_{proto}.png"), dpi=170); plt.close()
        # ---- size head quality ----
        sh = d[d.t_hat.notna() & d.variant.isin(["roy_size", "roy_full"])]
        if len(sh):
            md.append(f"\n## Protocol {proto}: how well the size head predicts the polyp size\n")
            md.append("| version | test set | n | mean error in size code | typical area error (median, %) | correlation |\n|---|---|---|---|---|---|")
            fig, axes = plt.subplots(1, 2, figsize=(9, 4), sharex=True, sharey=True)
            for ax, v in zip(axes, ["roy_size", "roy_full"]):
                for s in sets:
                    x = sh[(sh.variant == v) & (sh.set == s)]
                    if not len(x): continue
                    ae = np.abs(10 ** (3 * x.t_hat - 3) / x.area_frac - 1) * 100
                    md.append(f"| {v} | {s} | {len(x)} | {np.abs(x.t_hat - x.t_gt).mean():.3f} | {np.median(ae):.0f} | {np.corrcoef(x.t_hat, x.t_gt)[0, 1]:.3f} |")
                    ax.scatter(x.t_gt, x.t_hat, s=6, alpha=.5, label=s)
                ax.plot([0, 1], [0, 1], "k--", lw=.8); ax.set_title(NICE[v], fontsize=9); ax.set_xlabel("true size code"); ax.grid(alpha=.3)
            axes[0].set_ylabel("predicted size code"); axes[0].legend(fontsize=6); plt.suptitle(f"Protocol {proto}: size head, predicted vs true polyp size (0 = tiny, 1 = whole picture)", fontsize=10); plt.tight_layout(); plt.savefig(os.path.join(a.out, f"fig_size_head_{proto}.png"), dpi=170); plt.close()

    # ---- Protocol B vs published ----
    if "B" in set(clean.protocol):
        d = clean[clean.protocol == "B"]; fig, ax = plt.subplots(figsize=(9.5, 4)); names = list(PUBLISHED) + [f"ours: {v}" for v in sorted(set(d.variant), key=VARIANT_ORDER.index)]
        vals = [PUBLISHED[k] for k in PUBLISHED] + [[d[(d.variant == v) & (d.set == s)].dice.mean() for s in B_SETS] for v in sorted(set(d.variant), key=VARIANT_ORDER.index)]
        w = .8 / len(names); cols = ["#bbbbbb", "#999999", "#777777", "#555555", "#333333"] + [COL[v] for v in sorted(set(d.variant), key=VARIANT_ORDER.index)]
        for k, (n, v_) in enumerate(zip(names, vals)): ax.bar(np.arange(5) + k * w, v_, w, label=n, color=cols[k])
        ax.set_xticks(np.arange(5) + .4); ax.set_xticklabels(B_SETS); ax.set_ylim(.55, 1.0); ax.set_ylabel("Dice"); ax.grid(alpha=.3, axis="y"); ax.legend(fontsize=7, ncol=2)
        ax.set_title("Standard (PraNet) protocol: published single models vs ours (ours = 5-fold ensemble + flip TTA, one seed; NOT a controlled comparison)", fontsize=8); plt.tight_layout(); plt.savefig(os.path.join(a.out, "fig_protocolB_vs_published.png"), dpi=170); plt.close()
        md.append("\n## Protocol B against published numbers (Dice)\n\n| method | " + " | ".join(B_SETS) + " |\n|---|" + "---|" * 5)
        for n, v_ in zip(names, vals): md.append(f"| {n} | " + " | ".join(f"{x:.3f}" for x in v_) + " |")
        md.append("\nCaution: published rows are single models from each paper's own table; ours is a 5-fold ensemble with flip test-time augmentation, one seed, threshold from out-of-fold predictions. The ClinicDB-62 test frames share video sequences with the training frames (checked), so that column is partly a 'seen polyp' score for everyone.")

    # ---- training curves + speed ----
    hs = glob.glob(os.path.join(a.bundle, "runs", "A", "*", "seed*", "fold*", "history.json"))
    if hs:
        fig, ax = plt.subplots(figsize=(6.5, 3.8)); sp = []
        for v in [v for v in VARIANT_ORDER if any(f"/{v}/" in h.replace(os.sep, "/") for h in hs)]:
            H = [json.load(open(h)) for h in hs if f"/{v}/" in h.replace(os.sep, "/")]; L = max(len(h) for h in H)
            M = np.full((len(H), L), np.nan)
            for i, h in enumerate(H): M[i, :len(h)] = [e["val_dice"] for e in h]
            ok = (~np.isnan(M)).sum(0) >= 3; ep = np.arange(1, L + 1)[ok]; mu = np.nanmean(M, 0)[ok]
            ax.plot(ep, mu, color=COL[v], label=v); sp.append((v, np.median([e["sec"] for h in H for e in h]), np.mean([len(h) for h in H])))
        ax.set_ylim(.5, .95); ax.set_xlabel("epoch"); ax.set_ylabel("validation Dice (inner fold, mean over folds)"); ax.grid(alpha=.3); ax.legend(fontsize=7); ax.set_title("Protocol A training curves (training-side validation, not test)", fontsize=9)
        plt.tight_layout(); plt.savefig(os.path.join(a.out, "fig_training_curves_A.png"), dpi=170); plt.close()
        md.append("\n## Cost: parameters, speed, epochs\n\n| version | parameters (M) | s/epoch (median, 2 jobs per machine) | epochs per fold (mean) |\n|---|---|---|---|")
        for v, s_, e in sp: md.append(f"| {v} | {PARAMS_M.get(v, float('nan'))} | {s_:.0f} | {e:.1f} |")
    open(os.path.join(a.out, "ANALYSIS.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")
    print("wrote", os.path.join(a.out, "ANALYSIS.md"), "and", len(glob.glob(os.path.join(a.out, "*.png"))), "figures")


if __name__ == "__main__":
    main()
